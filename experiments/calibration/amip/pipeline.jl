# Three-input AMIP pipeline. See README.md.
#
# `amip_pipeline` takes a coupler YAML, parameters (a prior list), and
# observations (short names or a prebuilt observation vector). It writes a
# self-contained config file into the run directory, builds the
# observations, gates on preflight, and submits run_calibration.jl as a
# CPU-driver PBS job.
#
# The generated config is ordinary: every existing script can run it through
# ENV["CALIBRATION_CONFIG"], so a pipeline run can be inspected, repeated, or
# resumed exactly like a hand-written one.

import Dates
import JLD2
import ClimaCoupler
import ClimaCoupler: CalibrationTools
import EnsembleKalmanProcesses as EKP
import EnsembleKalmanProcesses.ParameterDistributions as PD

const AMIP_PROJECT = joinpath(pkgdir(ClimaCoupler), "experiments", "AMIP")
const AMIP_CAL_DIR = joinpath(pkgdir(ClimaCoupler), "experiments", "calibration", "amip")

# Variables that carry a structural model bias get the larger error floor by
# default (cl definitional gap, too-bright swcre).
const HIGH_FLOOR_VARS = ("cl", "swcre", "lwcre", "rsut", "rlut", "rsutcs", "rlutcs", "rsdt")

_julia_bin() = joinpath(Sys.BINDIR, Base.julia_exename())

_period_str(p::Dates.Period) = "Dates.$(nameof(typeof(p)))($(Dates.value(p)))"
_datetime_str(d::Dates.DateTime) = "Dates.DateTime(\"$(d)\")"
_range_str(r) = "($(_datetime_str(r[1])), $(_datetime_str(r[2])))"

"""
    default_noise_groups(short_names)

Floor of 0.2 for variables that track internal variability and 0.5 for
variables with a known structural bias.
"""
function default_noise_groups(short_names)
    low = filter(!in(HIGH_FLOOR_VARS), short_names)
    high = filter(in(HIGH_FLOOR_VARS), short_names)
    groups = NamedTuple[]
    isempty(low) || push!(groups, (short_names = low, model_error_scale = 0.2))
    isempty(high) || push!(groups, (short_names = high, model_error_scale = 0.5))
    return groups
end

function _run_logged(cmd, log_path, what)
    @info "$what (log: $log_path)"
    ok = success(pipeline(cmd; stdout = log_path, stderr = log_path))
    if !ok
        tail = join(last(readlines(log_path), 25), "\n")
        error("$what failed. Log tail:\n$tail")
    end
    return nothing
end

function _write_generated_config(
    path;
    config_file,
    short_names,
    output_dir,
    sample_date_ranges,
    covariance_date_ranges,
    spinup,
    extend,
    n_iterations,
    minibatch_size,
    noise_groups,
    reduction,
    rng_seed,
    pressure_levels,
    altitude_levels,
    worker_walltime,
    workers_per_node,
)
    sample_lines = join(("    $(_range_str(r))," for r in sample_date_ranges), "\n")
    cov_lines = join(("    $(_range_str(r))," for r in covariance_date_ranges), "\n")
    noise_lines = join(
        (
            "    (short_names = $(repr(collect(g.short_names))), " *
            "model_error_scale = $(g.model_error_scale))," for g in noise_groups
        ),
        "\n",
    )
    coarsen_block = reduction isa Integer ? "const COARSEN_FACTOR = $reduction\n\n" : ""

    priors_block = """
    const CALIBRATION_PRIORS =
        JLD2.load_object(joinpath(@__DIR__, "pipeline_priors.jld2"))
    """

    config = """
    # Generated by amip_pipeline on $(Dates.now()).
    # Inputs are stored next to this file.
    # Runnable by every calibration script through
    # ENV["CALIBRATION_CONFIG"] = "$path".

    config_file = "$config_file"

    sample_date_ranges = [
    $sample_lines
    ]

    const COVARIANCE_DATE_RANGES = [
    $cov_lines
    ]

    output_dir = "$output_dir"

    $(coarsen_block)const CALIBRATE_CONFIG = CalibrationTools.CalibrateConfig(;
        config_file,
        short_names = $(repr(short_names)),
        minibatch_size = $minibatch_size,
        n_iterations = $n_iterations,
        sample_date_ranges,
        extend = $(_period_str(extend)),
        spinup = $(_period_str(spinup)),
        output_dir,
        rng_seed = $rng_seed,
    )

    const OBS_NOISE_GROUPS = [
    $noise_lines
    ]

    const PRESSURE_LEVELS = $(repr(collect(pressure_levels)))
    const ALTITUDE_LEVELS = $(repr(collect(altitude_levels)))

    const NORMALIZATION_STATS_FP =
        joinpath(CALIBRATE_CONFIG.output_dir, "normalization_stats.jld2")

    const WORKER_WALLTIME = $worker_walltime
const WORKERS_PER_NODE = $workers_per_node

    $priors_block
    const PRIORS = EKP.combine_distributions(CALIBRATION_PRIORS)
    """
    write(path, config)
    return path
end

function _write_driver_pbs(pbs_path; name, output_dir, config_path)
    driver = "run_calibration.jl"
    jobname = "cal_" * first(name, 11)
    script = """
    #!/bin/bash
    #PBS -N $jobname
    #PBS -A UCIT0011
    #PBS -q main
    #PBS -l select=1:ncpus=16
    #PBS -l walltime=12:00:00
    #PBS -j oe
    #PBS -o $output_dir/driver.log

    # Generated by amip_pipeline. CPU driver, GPU workers or member jobs.
    cd $(pkgdir(ClimaCoupler)) || exit 1
    module purge
    module load climacommon/2025_02_25
    export CLIMACOMMS_DEVICE=CPU
    JULIA=$(_julia_bin())
    export JULIA_NUM_PRECOMPILE_TASKS=8
    export CALIBRATION_CONFIG=$config_path

    echo "=== \$(date) : instantiate ==="
    \$JULIA --project=experiments/AMIP -e 'using Pkg; Pkg.instantiate()'
    echo "=== \$(date) : run $driver (config=\$CALIBRATION_CONFIG) ==="
    \$JULIA --project=experiments/AMIP experiments/calibration/amip/$driver
    echo "=== \$(date) : exited \$? ==="
    """
    write(pbs_path, script)
    return pbs_path
end

"""
    amip_pipeline(config_file; parameters, observations, output_dir, kwargs...)

Run an AMIP calibration from three inputs.

# The three inputs
- `config_file`: coupler YAML (for example
  `config/amip_configs/amip_calibration.yml`).
- `parameters`: a `Vector` of `ParameterDistribution`.
- `observations`: variable short names (`["lwp", "pr"]`), resolved through
  the satellite catalog and built automatically, or a path to a prebuilt
  `observation_vec.jld2`.

# Required keyword
- `output_dir`: absolute path on scratch. Model output is large; never point
  this at home.

# Main options (validated defaults)
- `n_iterations = 8`,
- `reduction = :zonal` or an integer block-coarsening factor (4 = 10 deg),
- `sample_date_ranges`, `covariance_date_ranges`, `spinup`, `extend`,
- `noise_groups` (default: 0.2 floor, 0.5 for radiation-like variables),
- `short_names` (only needed when `observations` is a file path),
- `worker_walltime = 720`, `workers_per_node = 4`, `rng_seed = 42`,
- `skip_preflight = false`, `submit = true`.

The pipeline writes `generated_config.jl` plus the serialized inputs into
`output_dir`, builds the observation vector if needed, runs preflight (a
failure aborts before any GPU job), writes the driver PBS script, and
submits it. Returns `(; config_path, pbs_path, job_id)`.
"""
function amip_pipeline(
    config_file::AbstractString;
    parameters,
    observations,
    output_dir::AbstractString,
    short_names = nothing,
    sample_date_ranges = nothing,
    covariance_date_ranges = [
        (Dates.DateTime(y, 10, 1), Dates.DateTime(y, 10, 1)) for y in 2006:2010
    ],
    spinup::Dates.Period = Dates.Day(7),
    extend::Dates.Period = Dates.Month(1),
    n_iterations::Integer = 8,
    minibatch_size::Integer = 1,
    noise_groups = nothing,
    reduction = :zonal,
    rng_seed::Integer = 42,
    pressure_levels = 100.0 .* [200.0, 500.0, 850.0],
    altitude_levels = [2000.0, 5000.0, 10000.0],
    worker_walltime::Integer = 720,
    workers_per_node::Integer = 4,
    skip_preflight::Bool = false,
    submit::Bool = true,
)
    parameters isa AbstractVector{<:PD.ParameterDistribution} ||
        error("parameters must be a Vector of ParameterDistribution, got $(typeof(parameters))")
    isabspath(output_dir) ||
        error("output_dir must be an absolute path on scratch, got $output_dir")
    config_file = abspath(config_file)
    isfile(config_file) || error("config_file $config_file does not exist")
    reduction == :zonal ||
        reduction isa Integer ||
        error("reduction must be :zonal or an integer coarsening factor")

    short_names = if observations isa AbstractVector{<:AbstractString}
        collect(String, observations)
    elseif isnothing(short_names)
        error(
            "observations is a file path, so pass short_names (the variables " *
            "in the vector, in order)",
        )
    else
        collect(String, short_names)
    end

    if isnothing(sample_date_ranges)
        nsamp = n_iterations + 1
        sample_date_ranges =
            [(Dates.DateTime(2010, 10, 1), Dates.DateTime(2010, 10, 1)) for _ in 1:nsamp]
    end
    isnothing(noise_groups) && (noise_groups = default_noise_groups(short_names))

    mkpath(output_dir)
    JLD2.save_object(
        joinpath(output_dir, "pipeline_priors.jld2"),
        collect(PD.ParameterDistribution, parameters),
    )

    config_path = _write_generated_config(
        joinpath(output_dir, "generated_config.jl");
        config_file,
        short_names,
        output_dir,
        sample_date_ranges,
        covariance_date_ranges,
        spinup,
        extend,
        n_iterations,
        minibatch_size,
        noise_groups,
        reduction,
        rng_seed,
        pressure_levels,
        altitude_levels,
        worker_walltime,
        workers_per_node,
    )
    @info "Wrote $config_path"

    obs_path = joinpath(output_dir, "observation_vec.jld2")
    if observations isa AbstractVector{<:AbstractString}
        if isfile(obs_path)
            @info "Reusing existing observation vector" obs_path
        else
            cmd = addenv(
                `$(_julia_bin()) --project=$AMIP_PROJECT $(joinpath(AMIP_CAL_DIR, "generate_observations.jl"))`,
                "CALIBRATION_CONFIG" => config_path,
                "CLIMACOMMS_CONTEXT" => "SINGLETON",
            )
            _run_logged(
                cmd,
                joinpath(output_dir, "generate_observations.log"),
                "Building observations for $(short_names)",
            )
        end
    elseif observations isa AbstractString
        isfile(observations) || error("observation vector $observations not found")
        if isfile(obs_path)
            @info "Reusing existing observation vector" obs_path
        elseif abspath(observations) != obs_path
            cp(observations, obs_path)
        end
        # The simulation side samples the observation's coverage through the
        # masks saved next to the vector. Carry them along when present.
        masks_src = joinpath(dirname(abspath(observations)), "coverage_masks.jld2")
        masks_dst = joinpath(output_dir, "coverage_masks.jld2")
        if isfile(masks_src) && masks_src != masks_dst
            cp(masks_src, masks_dst; force = true)
        elseif !isfile(masks_dst)
            @warn "No coverage_masks.jld2 next to the observation vector. " *
                  "Variables with partial satellite coverage will be compared " *
                  "without masking."
        end
    else
        error(
            "observations is required: pass short names to build from the " *
            "catalog, or a path to a prebuilt observation_vec.jld2",
        )
    end

    if skip_preflight
        @warn "Preflight skipped"
    else
        cmd = `$(_julia_bin()) --project=$AMIP_PROJECT $(joinpath(AMIP_CAL_DIR, "preflight.jl")) $config_path`
        _run_logged(cmd, joinpath(output_dir, "preflight.log"), "Preflight")
        @info "Preflight passed"
    end

    name = basename(rstrip(output_dir, '/'))
    pbs_path = _write_driver_pbs(
        joinpath(output_dir, "submit_$name.pbs");
        name,
        output_dir,
        config_path,
    )

    job_id = nothing
    if submit
        job_id = readchomp(`qsub $pbs_path`)
        @info "Submitted calibration driver" job_id pbs_path
    else
        @info "Driver ready, not submitted. Submit with: qsub $pbs_path"
    end
    return (; config_path, pbs_path, job_id)
end
