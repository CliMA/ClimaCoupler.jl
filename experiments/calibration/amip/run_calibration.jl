using Dates
import Random
import ClimaCalibrate
import ClimaAnalysis
import ClimaCoupler
import ClimaCoupler: CalibrationTools
import EnsembleKalmanProcesses as EKP
import EnsembleKalmanProcesses.ParameterDistributions as PD
import JLD2
import YAML

model_interface_filepath = joinpath(
    pkgdir(ClimaCoupler),
    "experiments",
    "calibration",
    "amip",
    "model_interface.jl",
)
include(model_interface_filepath)

# Choose which calibration config to use
config_dir = joinpath(pkgdir(ClimaCoupler), "experiments", "calibration", "amip", "config")
default_config_path = joinpath(config_dir, "pressure_levels.jl")

test_calibration_config_path = joinpath(config_dir, "pipeline_test.jl")
const TEST_CALIBRATION = haskey(ENV, "TEST_CALIBRATION")

# Allow selecting an alternate config via ENV (e.g. one generated by
# pipeline.jl), so multiple calibration setups can share this driver. Falls
# back to the test config or the default lwp+cl config.
config_path = if haskey(ENV, "CALIBRATION_CONFIG")
    ENV["CALIBRATION_CONFIG"]
elseif TEST_CALIBRATION
    test_calibration_config_path
else
    default_config_path
end

@info "Using calibration configuration in: $config_path"
include(config_path)

# Fail before submitting anything if the `_E#` element priors do not splice
# cleanly into the run's parameter files; a mismatch caught later would fail
# on a worker mid-calibration.
CalibrationTools.check_element_priors(
    PD.get_name(PRIORS),
    CalibrationTools.parameter_dict(YAML.load_file(CALIBRATE_CONFIG.config_file)),
)

(; output_dir) = CALIBRATE_CONFIG
isdir(output_dir) || mkdir(output_dir)

if abspath(PROGRAM_FILE) == @__FILE__
    # The observation vector lives in the config's output_dir so that different
    # calibration setups (e.g. lwp+cl vs LWP-only) keep independent observations.
    observation_vector_filepath = joinpath(output_dir, "observation_vec.jld2")
    isfile(observation_vector_filepath) || error(
        "Filepath to observation vector is not valid. Update the filepath or generate the observations using generate_observations.jl",
    )
    observation_vector = JLD2.load_object(observation_vector_filepath)

    (; sample_date_ranges, minibatch_size) = CALIBRATE_CONFIG
    obs_series = EKP.ObservationSeries(
        Dict(
            "observations" => observation_vector,
            "names" => [
                string(Dates.year(start_date)) for
                (start_date, stop_date) in sample_date_ranges
            ],
            "minibatcher" => ClimaCalibrate.minibatcher_over_samples(
                length(observation_vector),
                minibatch_size,
            ),
        ),
    )

    (; rng_seed) = CALIBRATE_CONFIG
    rng = Random.MersenneTwister(rng_seed)

    # Use a gentle fixed timestep instead of DataMisfitController. DMC has no
    # step-size knob and, with an over-informative observation, collapsed the
    # ensemble covariance ~3 orders of magnitude in a single step — pinning the
    # parameters near the prior mean before any weak signal could be exploited.
    # A small fixed Δt spreads the update over many iterations: accumulated
    # pseudo-time T reaches ~1 (the full posterior) over 1/Δt steps, so set
    # n_iterations ≈ 1/Δt in the config (Δt = 0.1 → n_iterations = 10).
    ekp = EKP.EnsembleKalmanProcess(
        obs_series,
        EKP.TransformUnscented(PRIORS, impose_prior = true);
        verbose = true,
        rng,
        scheduler = EKP.DefaultScheduler(0.1),
    )

    coupler_model_interface = CouplerModelInterface(CALIBRATE_CONFIG)
    (; n_iterations, output_dir) = CALIBRATE_CONFIG

    # Record the priors the run starts from (constrained-space marginals).
    plot_priors(PRIORS, output_dir)

    # Async workers (ClimaCalibrate >= 0.4): persistent workers run ensemble
    # members concurrently and are reused across iterations, instead of
    # submitting one PBS job per member per iteration.
    # The smoke test runs on CPU within an existing allocation, while a full
    # calibration puts ensemble members on GPUs.
    device = TEST_CALIBRATION ? :cpu : :gpu
    # A config (for example one generated by pipeline.jl) may override the
    # worker walltime and packing.
    walltime = @isdefined(WORKER_WALLTIME) ? WORKER_WALLTIME :
               TEST_CALIBRATION ? 60 : 720
    # Pack 4 workers per allocation, one per GPU. Derecho charges exclusive
    # jobs for all 4 GPUs of a node no matter how many are requested, so
    # unpacked workers cost 4x the GPU-hours they use. Peak member host
    # memory is ~26 GB (measured over the July runs), so 4 members fit the
    # 487 GB node with a wide margin.
    workers_per_node = @isdefined(WORKERS_PER_NODE) ? WORKERS_PER_NODE : 4
    env_vars = [
        "CLIMACOMMS_CONTEXT" => "SINGLETON",
        "CLIMACOMMS_DEVICE" => TEST_CALIBRATION ? "CPU" : "CUDA",
    ]
    # Workers advertise getipaddr(), the management network on Derecho, which
    # login nodes cannot reach. A driver outside PBS (tmux on a login node)
    # must set CALIBRATION_WORKER_EXENAME to julia_worker_hsn_bind.sh so
    # workers bind to the HSN, which login and compute nodes share.
    exename_kwargs = haskey(ENV, "CALIBRATION_WORKER_EXENAME") ?
        (; exename = ENV["CALIBRATION_WORKER_EXENAME"]) : (;)
    # Keep worker PBS logs with the run. Without `o`, ClimaCalibrate puts them
    # under a mktempdir (.julia_worker_*) whose default cleanup=true deletes
    # them when the driver exits - which is how the rlut_pigroups member-2 NaN
    # left no worker-side record. `o` is a filename PREFIX: workers write
    # <prefix>-<job>-<slot>.out next to driver.log.
    worker_log_prefix = joinpath(output_dir, "worker_logs", "worker")
    mkpath(dirname(worker_log_prefix))
    if TEST_CALIBRATION
        # CPU workers inside the current allocation; no packing (local
        # processing starts each worker as its own process).
        ClimaCalibrate.add_workers(
            EKP.get_N_ens(ekp);
            device,
            time = walltime,
            env = env_vars,
            mem = "16GB",
            o = worker_log_prefix,
            exename_kwargs...,
        )
    else
        # Packed GPU workers; allocation resources (memory, select line) are
        # sized by ClimaCalibrate from workers_per_node.
        ClimaCalibrate.add_workers(
            EKP.get_N_ens(ekp);
            device,
            time = walltime,
            workers_per_node,
            env = env_vars,
            o = worker_log_prefix,
            exename_kwargs...,
        )
    end
    # Load the model interface on every worker, including any that join later.
    ClimaCalibrate.@worker_setup include($model_interface_filepath)

    # Worker jobs can wait in the GPU queue far longer than the default
    # 2 h empty-pool timeout, which only counts CONNECTED workers. A busy
    # queue then kills a healthy driver whose workers are merely queued
    # (this killed the lwp+cl+swcre zonal run on 2026-07-28). Give the
    # pool the driver's full walltime instead.
    eki = ClimaCalibrate.calibrate(
        ClimaCalibrate.WorkerBackend(; empty_pool_timeout = 11 * 3600),
        ekp,
        coupler_model_interface,
        n_iterations,
        PRIORS,
        output_dir,
    )
end
